#!/usr/bin/env python3
# ruff: noqa: E501  (templates that emit Kotlin/JS contain long lines)
"""Generate platform files from design/tokens/mia.tokens.json (W3C Design Tokens).

Outputs
  web/src/styles/tokens.css          CSS custom properties (--mia-*)
  design/generated/MiaTokens.kt      Android Kotlin source (canonical copy)
  design/preview/tokens.generated.js token lists for the style page (design/preview/index.html)
  <android-dir>/core/designsystem/src/main/kotlin/by/mia/assistant/core/designsystem/MiaTokens.kt
                                     same file, written when --android-dir / MIA_ANDROID_DIR is given

Usage
  python design/scripts/build_tokens.py [--android-dir DIR] [--check]

--check writes nothing and exits 1 when any existing generated file differs from the source.
Output is deterministic: no timestamps, only the SHA-256 of the source file.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "design" / "tokens" / "mia.tokens.json"
CSS_OUT = ROOT / "web" / "src" / "styles" / "tokens.css"
KT_CANONICAL = ROOT / "design" / "generated" / "MiaTokens.kt"
JS_OUT = ROOT / "design" / "preview" / "tokens.generated.js"
KT_ANDROID_REL = Path(
    "core/designsystem/src/main/kotlin/by/mia/assistant/core/designsystem/MiaTokens.kt"
)
THEMES = ("dark", "light")
HEX_RE = re.compile(r"^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$")
HEADER = (
    "GENERATED by design/scripts/build_tokens.py from design/tokens/mia.tokens.json. Do not edit."
)


def load() -> tuple[dict[str, Any], str]:
    raw = SOURCE.read_bytes()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def val(node: dict[str, Any], *path: str) -> Any:
    for part in path:
        node = node[part]
    return node["$value"]


def leaves(group: dict[str, Any]) -> list[tuple[str, Any]]:
    """Direct children carrying `$value`, in source order."""
    return [(k, v["$value"]) for k, v in group.items() if not k.startswith("$") and "$value" in v]


def check_hex(value: str) -> str:
    if not HEX_RE.match(value):
        raise ValueError(f"not a #rrggbb[aa] color: {value!r}")
    return value.lower()


def css_color(value: str) -> str:
    return check_hex(value)


def px_num(value: str) -> float:
    assert value.endswith("px"), value
    return float(value[:-2])


def ms_num(value: str) -> int:
    assert value.endswith("ms"), value
    return int(value[:-2])


def num(x: float) -> str:
    return str(int(x)) if float(x) == int(x) else repr(float(x))


def resolve_ref(tokens: dict[str, Any], ref: Any) -> Any:
    if isinstance(ref, str) and ref.startswith("{") and ref.endswith("}"):
        node: Any = tokens
        for part in ref[1:-1].split("."):
            node = node[part]
        return node["$value"]
    return ref


def css_shadow(layers: list[dict[str, str]]) -> str:
    return ", ".join(
        f"{s['offsetX']} {s['offsetY']} {s['blur']} {s['spread']} {css_color(s['color'])}"
        for s in layers
    )


def css_family(families: list[str]) -> str:
    return ", ".join(f"'{f}'" if " " in f else f for f in families)


# ---------------------------------------------------------------- CSS


def theme_vars(tokens: dict[str, Any], theme: str) -> list[str]:
    out = [f"color-scheme: {theme};"]
    for key, value in leaves(tokens["color"][theme]):
        out.append(f"--mia-color-{key}: {css_color(value)};")
    for level, node in tokens["shadow"][theme].items():
        out.append(f"--mia-shadow-{level}: {css_shadow(node['$value'])};")
    out.append(f"--mia-aurora-opacity: {num(val(tokens['gradient']['aurora-opacity'], theme))};")
    return out


def build_css(tokens: dict[str, Any], digest: str) -> str:
    base: list[str] = []
    for key, value in leaves(tokens["radius"]):
        base.append(f"--mia-radius-{key}: {value};")
    for key, value in leaves(tokens["space"]):
        base.append(f"--mia-space-{key}: {value};")
    for key, value in leaves(tokens["size"]):
        base.append(f"--mia-size-{key}: {value};")
    for key, value in leaves(tokens["blur"]):
        base.append(f"--mia-blur-{key}: {value};")
    fam = tokens["font"]["family"]
    for key, value in leaves(fam):
        base.append(f"--mia-font-{key}: {css_family(value)};")
    for key, value in leaves(tokens["font"]["weight"]):
        base.append(f"--mia-weight-{key}: {value};")
    for name, node in tokens["type"].items():
        if name.startswith("$"):
            continue
        t = node["$value"]
        base.append(f"--mia-type-{name}-size: {t['fontSize']};")
        base.append(f"--mia-type-{name}-weight: {resolve_ref(tokens, t['fontWeight'])};")
        base.append(f"--mia-type-{name}-line: {num(t['lineHeight'])};")
        base.append(f"--mia-type-{name}-tracking: {t['letterSpacing']};")
    for key, value in leaves(tokens["motion"]["duration"]):
        base.append(f"--mia-dur-{key}: {value};")
    for key, value in leaves(tokens["motion"]["easing"]):
        base.append(f"--mia-ease-{key}: cubic-bezier({', '.join(num(x) for x in value)});")
    spring = tokens["motion"]["spring"]
    base.append(f"--mia-spring-stiffness: {num(val(spring, 'stiffness'))};")
    base.append(f"--mia-spring-damping-ratio: {num(val(spring, 'damping-ratio'))};")
    for key, value in leaves(tokens["breakpoint"]):
        base.append(f"--mia-bp-{key}: {value};")
    stops = ", ".join(
        f"{css_color(s['color'])} {num(s['position'] * 100)}%"
        for s in val(tokens["gradient"], "accent")
    )
    base.append(f"--mia-gradient-accent: linear-gradient(135deg, {stops});")

    def block(selector: str, lines: list[str], indent: str = "") -> str:
        body = "\n".join(f"{indent}  {line}" for line in lines)
        return f"{indent}{selector} {{\n{body}\n{indent}}}\n"

    parts = [
        f"/* {HEADER}\n   source-sha256: {digest} */\n",
        block(":root", base),
        # [data-mia-theme] scopes a theme to a subtree (style page shows both themes side by side).
        block(
            ":root,\n:root[data-theme='dark'],\n[data-mia-theme='dark']", theme_vars(tokens, "dark")
        ),
        "@media (prefers-color-scheme: light) {\n"
        + block(":root:not([data-theme])", theme_vars(tokens, "light"), "  ")
        + "}\n",
        block(":root[data-theme='light'],\n[data-mia-theme='light']", theme_vars(tokens, "light")),
    ]
    return "\n".join(parts)


# ---------------------------------------------------------------- Kotlin


def camel(key: str) -> str:
    parts = re.split(r"[-_]", key)
    name = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return name if not name[0].isdigit() else "s" + name


def pascal(key: str) -> str:
    c = camel(key)
    return c[:1].upper() + c[1:]


def kt_color(value: str) -> str:
    h = check_hex(value)[1:]
    if len(h) == 6:
        h = "ff" + h
    else:
        h = h[6:] + h[:6]  # rrggbbaa -> aarrggbb
    return f"Color(0x{h.upper()})"


def kt_float(x: float) -> str:
    return f"{x:g}f" if x != int(x) else f"{int(x)}f"


def kt_dp(value: str) -> str:
    return f"{num(px_num(value))}.dp"


def build_kotlin(tokens: dict[str, Any], digest: str) -> str:
    L: list[str] = []
    a = L.append
    a(f"// {HEADER}")
    a(f"// source-sha256: {digest}")
    a('@file:Suppress("unused", "MagicNumber")')
    a("")
    a("package by.mia.assistant.core.designsystem")
    a("")
    for imp in (
        "androidx.compose.animation.core.CubicBezierEasing",
        "androidx.compose.ui.graphics.Color",
        "androidx.compose.ui.text.TextStyle",
        "androidx.compose.ui.text.font.FontWeight",
        "androidx.compose.ui.unit.Dp",
        "androidx.compose.ui.unit.dp",
        "androidx.compose.ui.unit.em",
        "androidx.compose.ui.unit.sp",
    ):
        a(f"import {imp}")
    a("")
    color_keys = [k for k, _ in leaves(tokens["color"]["dark"])]
    assert color_keys == [k for k, _ in leaves(tokens["color"]["light"])], "theme keys differ"
    a("/** One depth layer of a shadow. */")
    a(
        "class MiaShadowLayer(val color: Color, val offsetX: Dp, val offsetY: Dp, val blur: Dp, val spread: Dp)"
    )
    a("")
    a("/** Colors of one theme; names mirror `--mia-color-*` in tokens.css. */")
    a("class MiaColors(")
    for k in color_keys:
        a(f"    val {camel(k)}: Color,")
    a(") {")
    a("    /** Aurora blob colors in drawing order. */")
    a("    val aurora: List<Color> get() = listOf(aurora1, aurora2, aurora3)")
    a("}")
    a("")
    a("/** Depth levels 1..3 of one theme. */")
    a(
        "class MiaShadows(val level1: List<MiaShadowLayer>, val level2: List<MiaShadowLayer>, val level3: List<MiaShadowLayer>)"
    )
    a("")
    a("object MiaTokens {")
    a(f'    const val SOURCE_SHA256: String = "{digest}"')
    a("")
    for theme in THEMES:
        a(f"    val {pascal(theme)}Colors: MiaColors = MiaColors(")
        for k, v in leaves(tokens["color"][theme]):
            a(f"        {camel(k)} = {kt_color(v)},")
        a("    )")
        a("")
    for theme in THEMES:
        a(f"    val {pascal(theme)}Shadows: MiaShadows = MiaShadows(")
        for level in ("1", "2", "3"):
            layers = tokens["shadow"][theme][level]["$value"]
            inner = ", ".join(
                f"MiaShadowLayer({kt_color(s['color'])}, {kt_dp(s['offsetX'])}, {kt_dp(s['offsetY'])}, {kt_dp(s['blur'])}, {kt_dp(s['spread'])})"
                for s in layers
            )
            a(f"        level{level} = listOf({inner}),")
        a("    )")
        a("")
    for theme in THEMES:
        a(
            f"    const val {pascal(theme)}AuroraOpacity: Float = {kt_float(val(tokens['gradient']['aurora-opacity'], theme))}"
        )
    a("")
    a("    /** Accent button gradient, 135deg, first to last stop. */")
    a(
        "    val GradientAccent: List<Color> = listOf("
        + ", ".join(kt_color(s["color"]) for s in val(tokens["gradient"], "accent"))
        + ")"
    )
    a("")
    a("    object Radius {")
    for k, v in leaves(tokens["radius"]):
        a(f"        val {camel(k)}: Dp = {kt_dp(v)}")
    a("    }")
    a("")
    a("    object Space {")
    for k, v in leaves(tokens["space"]):
        a(f"        val {camel(k)}: Dp = {kt_dp(v)}")
    a("    }")
    a("")
    a("    object Size {")
    for k, v in leaves(tokens["size"]):
        a(f"        val {camel(k)}: Dp = {kt_dp(v)}")
    a("    }")
    a("")
    a("    object Blur {")
    for k, v in leaves(tokens["blur"]):
        a(f"        val {camel(k)}: Dp = {kt_dp(v)}")
    a("    }")
    a("")
    a(
        "    /** Font families by token name; Android uses the system sans until Manrope is bundled. */"
    )
    a("    object FontFamilies {")
    for k, v in leaves(tokens["font"]["family"]):
        a(f"        val {camel(k)}: List<String> = listOf({', '.join(json.dumps(x) for x in v)})")
    a("    }")
    a("")
    a("    object Type {")
    for name, node in tokens["type"].items():
        if name.startswith("$"):
            continue
        t = node["$value"]
        size = px_num(t["fontSize"])
        weight = resolve_ref(tokens, t["fontWeight"])
        tracking = float(t["letterSpacing"].removesuffix("em"))
        a(
            f"        val {camel(name)}: TextStyle = TextStyle(fontSize = {num(size)}.sp, "
            f"lineHeight = {num(round(size * t['lineHeight'], 2))}.sp, "
            f"fontWeight = FontWeight({weight}), letterSpacing = {num(tracking)}.em)"
        )
    a("    }")
    a("")
    a("    object Motion {")
    for k, v in leaves(tokens["motion"]["duration"]):
        a(f"        const val Duration{pascal(k)}Ms: Int = {ms_num(v)}")
    for k, v in leaves(tokens["motion"]["easing"]):
        a(
            f"        val Easing{pascal(k)}: CubicBezierEasing = CubicBezierEasing({', '.join(kt_float(x) for x in v)})"
        )
    spring = tokens["motion"]["spring"]
    a(f"        const val SpringStiffness: Float = {kt_float(val(spring, 'stiffness'))}")
    a(f"        const val SpringDampingRatio: Float = {kt_float(val(spring, 'damping-ratio'))}")
    a("    }")
    a("")
    a("    object Breakpoint {")
    for k, v in leaves(tokens["breakpoint"]):
        a(f"        val {camel(k)}: Dp = {kt_dp(v)}")
    a("    }")
    a("}")
    a("")
    return "\n".join(L)


def build_js(tokens: dict[str, Any], digest: str) -> str:
    """Plain data for the static style page; CSS custom properties supply the values at runtime."""
    data = {
        "sourceSha256": digest,
        "colors": [k for k, _ in leaves(tokens["color"]["dark"])],
        "hex": {t: dict(leaves(tokens["color"][t])) for t in THEMES},
        "radius": dict(leaves(tokens["radius"])),
        "space": dict(leaves(tokens["space"])),
        "type": [n for n in tokens["type"] if not n.startswith("$")],
        "shadows": ["1", "2", "3"],
        "durations": dict(leaves(tokens["motion"]["duration"])),
        "easings": {k: v for k, v in leaves(tokens["motion"]["easing"])},
        "breakpoints": dict(leaves(tokens["breakpoint"])),
        "touch": {
            "web": val(tokens["size"], "touch-web"),
            "android": val(tokens["size"], "touch-android"),
        },
    }
    return f"// {HEADER}\n// source-sha256: {digest}\nwindow.MIA_TOKENS = {json.dumps(data, indent=2, ensure_ascii=False)};\n"


# ---------------------------------------------------------------- driver


def outputs(android_dir: Path | None) -> dict[Path, str]:
    tokens, digest = load()
    css = build_css(tokens, digest)
    kt = build_kotlin(tokens, digest)
    result = {CSS_OUT: css, KT_CANONICAL: kt, JS_OUT: build_js(tokens, digest)}
    if android_dir is not None:
        result[android_dir / KT_ANDROID_REL] = kt
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--android-dir", default=os.environ.get("MIA_ANDROID_DIR"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    android = Path(args.android_dir).resolve() if args.android_dir else None
    drift = 0
    for path, content in outputs(android).items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                print(f"DRIFT {path}")
                drift = 1
            else:
                print(f"ok    {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path}")
    return drift


if __name__ == "__main__":
    sys.exit(main())

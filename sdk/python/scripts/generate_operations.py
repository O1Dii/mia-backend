"""Generate the SDK operation tables from ``contracts/mvp/v1/openapi.yaml`` (M50).

Both SDKs are thin wrappers: method, path template, required OAuth scopes and the
idempotency rule of every operation tagged ``Apps``, ``Runs`` or ``Memory`` come from the
contract, so the SDKs follow the API without hand edits.

    uv run python sdk/python/scripts/generate_operations.py          # write
    uv run python sdk/python/scripts/generate_operations.py --check  # CI drift check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml  # type: ignore[import-untyped]

ROOT = Path(__file__).resolve().parents[3]
OPENAPI = ROOT / "contracts/mvp/v1/openapi.yaml"
PYTHON_OUT = ROOT / "sdk/python/src/mia_sdk/_operations.py"
JS_OUT = ROOT / "sdk/js/src/operations.ts"
TAGS = {"Apps", "Runs", "Memory"}
METHODS = ("get", "post", "put", "patch", "delete")
BANNER = "GENERATED by sdk/python/scripts/generate_operations.py from openapi.yaml. Do not edit."


def operations(spec: dict[str, Any]) -> list[dict[str, Any]]:
    found = []
    for path, item in spec["paths"].items():
        for method in METHODS:
            operation = item.get(method)
            if not operation or not TAGS & set(operation.get("tags", [])):
                continue
            scopes: list[str] = []
            for requirement in operation.get("security", spec.get("security", [])):
                scopes.extend(requirement.get("miaOAuth", []))
            idempotent = any(
                p.get("$ref") == "#/components/parameters/IdempotencyKey"
                for p in operation.get("parameters", [])
            )
            found.append(
                {
                    "id": operation["operationId"],
                    "method": method.upper(),
                    "path": path,
                    "scopes": sorted(set(scopes)),
                    "idempotency_key": idempotent,
                }
            )
    return sorted(found, key=lambda op: op["id"])


def render_python(ops: list[dict[str, Any]], version: str) -> str:
    lines = [
        f'"""{BANNER}"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Final, TypedDict",
        "",
        "",
        "class Operation(TypedDict):",
        "    method: str",
        "    path: str",
        "    scopes: tuple[str, ...]",
        "    idempotency_key: bool",
        "",
        "",
        f"API_VERSION: Final = {version!r}",
        "OPERATIONS: Final[dict[str, Operation]] = {",
    ]
    for op in ops:
        scopes = "(" + "".join(f"{s!r}, " for s in op["scopes"]).rstrip(" ") + ")"
        lines.append(
            f"    {op['id']!r}: {{\n"
            f'        "method": {op["method"]!r},\n'
            f'        "path": {op["path"]!r},\n'
            f'        "scopes": {scopes},\n'
            f'        "idempotency_key": {op["idempotency_key"]},\n'
            "    },"
        )
    lines.append("}")
    return "\n".join(lines).replace("'", '"') + "\n"


def render_js(ops: list[dict[str, Any]], version: str) -> str:
    table = {
        op["id"]: {
            "method": op["method"],
            "path": op["path"],
            "scopes": op["scopes"],
            "idempotencyKey": op["idempotency_key"],
        }
        for op in ops
    }
    return (
        f"// {BANNER}\n"
        "export type Operation = {\n"
        "  method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'\n"
        "  path: string\n"
        "  scopes: readonly string[]\n"
        "  idempotencyKey: boolean\n"
        "}\n\n"
        f"export const API_VERSION = {json.dumps(version)}\n\n"
        "export const OPERATIONS = "
        + json.dumps(table, indent=2, ensure_ascii=False)
        + " as const satisfies Record<string, Operation>\n\n"
        "export type OperationId = keyof typeof OPERATIONS\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = yaml.safe_load(OPENAPI.read_text("utf-8"))
    ops = operations(spec)
    version = str(spec["info"]["version"])
    outputs = {PYTHON_OUT: render_python(ops, version), JS_OUT: render_js(ops, version)}
    stale = [
        path for path, text in outputs.items() if not path.exists() or path.read_text() != text
    ]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, "utf-8")
    print(f"{len(ops)} operations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
